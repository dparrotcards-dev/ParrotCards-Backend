export async function seedCardDefinitions(): Promise<void> {
  console.log('🌱 Seeding 55 approved Parrot Cards definitions into database...');
  for (const card of APPROVED_55_CARDS) {
    const cardId = `${card.suit.toUpperCase()}_${card.rank.replace(/\s+/g, '_')}_${card.position}`;
    await CardDefinition.findOneAndUpdate(
      { position: card.position },
      {
        $set: {
          cardId,
          suit: card.suit,
          suitSymbol: card.suitSymbol,
          suitName: card.suitName,
          suitTheme: card.suitTheme,
          rank: card.rank,
          label: card.label,
          key: card.key,
          title: card.title,
          line: card.line,
          shortSummary: card.shortSummary,
          detailedInterpretation: card.detailedInterpretation,
          reflectionQuestion: card.reflectionQuestion,
          position: card.position,
          isFreeByDefault: card.isFreeByDefault,
          category: card.category,
        },
      },
      { upsert: true, new: true }
    );
  }
  const count = await CardDefinition.countDocuments();
  console.log(`✅ Successfully seeded and verified ${count} card definitions!`);
}

// Standalone execution support
if (require.main === module) {
  connectDB()
    .then(() => seedCardDefinitions())
    .then(() => disconnectDB())
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('❌ Seeding error:', err);
      process.exit(1);
    });
}
